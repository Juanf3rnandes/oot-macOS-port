#!/usr/bin/env python3
"""
Generates the list of game C sources for the native build from spec/ (docs/port-macos/adr/0005-build-cmake-separado.md).

The spec is preprocessed with the same version macros as the matching build, so files that only exist in some
versions are picked automatically. Directories replaced by the port (libultra, 64DD, libgcc...) are excluded.

Output: a CMake file defining
    OOT_SPEC_GAME_SOURCES     game .c files (repo-relative) in spec order
    OOT_SPEC_ASSET_SOURCES    asset .c files (relative to extracted/<version>/) in spec order
    OOT_SPEC_SKIPPED          spec entries not compiled natively (assembly, binary data, replaced code)
    OOT_SPEC_NEED_ASSETS      game sources that include headers extracted from the ROM (only with --check-assets)
"""

from __future__ import annotations

import argparse
import concurrent.futures
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# Replaced by the port shim or out of scope. See docs/port-macos/04-arquitetura-do-port.md §6.
EXCLUDED_DIRS = (
    "src/libultra/",  # replaced by port/src/ultra (a few pure-C files are added back by CMake)
    "src/libleo/",    # 64DD, out of scope
    "src/n64dd/",     # 64DD, out of scope
    "src/libgcc/",    # MIPS compiler runtime
    "src/makerom/",   # ROM header / entry point
    "src/gcc_fix/",
)

INCLUDE_RE = re.compile(r'^\s*include\s+"\*?\$\(BUILD_DIR\)/([^"]+)\.o"', re.M)


def preprocess_spec(defines: list[str]) -> str:
    cmd = ["clang", "-E", "-P", "-xc", "-Ispec", "-I.", *[f"-D{d}" for d in defines], "spec/spec"]
    return subprocess.run(cmd, cwd=REPO, check=True, capture_output=True, text=True).stdout


def needs_assets(src: str, cflags: list[str], asset_dirs: list[Path]) -> bool:
    """True if `src` (transitively) includes a header that does not exist yet or comes from the ROM extraction."""
    cmd = ["clang", "-MM", "-MG", "-xc", *cflags, src]
    res = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    if res.returncode != 0:
        return True
    deps = res.stdout.replace("\\\n", " ").split()[1:]
    for dep in deps:
        path = Path(dep) if os.path.isabs(dep) else REPO / dep
        if not path.exists():
            return True
        if any(d in path.resolve().parents for d in asset_dirs):
            return True
    return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--define", "-D", action="append", default=[], help="version macro, e.g. OOT_VERSION=GC_EU_MQ_DBG")
    ap.add_argument("--output", "-o", required=True)
    ap.add_argument("--check-assets", action="store_true", help="classify sources that need extracted assets")
    ap.add_argument("--cflag", action="append", default=[], help="compiler flag used by --check-assets")
    ap.add_argument("--asset-dir", action="append", default=[], help="directory with ROM-derived files")
    args = ap.parse_args()

    spec = preprocess_spec(args.define)
    game, assets, skipped = [], [], []
    seen = set()
    for stem in INCLUDE_RE.findall(spec):
        if stem in seen:
            continue
        seen.add(stem)
        if stem.startswith("src/"):
            if stem.startswith(EXCLUDED_DIRS) or stem.endswith("_reloc"):
                skipped.append(stem)
            elif (REPO / f"{stem}.c").exists():
                game.append(f"{stem}.c")
            else:
                skipped.append(stem)  # assembly (.s) or generated file
        elif stem.startswith("assets/"):
            assets.append(f"{stem}.c")
        else:
            skipped.append(stem)  # data/, baserom/, rsp/ binaries

    need_assets: list[str] = []
    if args.check_assets:
        asset_dirs = [Path(d).resolve() for d in args.asset_dir]
        with concurrent.futures.ThreadPoolExecutor(os.cpu_count()) as ex:
            flags = list(ex.map(lambda src: needs_assets(src, args.cflag, asset_dirs), game))
        need_assets = [src for src, flag in zip(game, flags) if flag]

    def cmake_list(name: str, items: list[str]) -> str:
        body = "\n".join(f"    {i}" for i in items)
        return f"set({name}\n{body}\n)\n"

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "# Generated by port/tools/gen_game_sources.py from spec/. Do not edit.\n"
    text += cmake_list("OOT_SPEC_GAME_SOURCES", game)
    text += cmake_list("OOT_SPEC_ASSET_SOURCES", assets)
    text += cmake_list("OOT_SPEC_SKIPPED", skipped)
    text += cmake_list("OOT_SPEC_NEED_ASSETS", need_assets)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"gen_game_sources: {len(game)} game sources ({len(need_assets)} need extracted assets), "
          f"{len(assets)} asset sources, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
